import os
import sys
import platform
from rich.box import Box
from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text
from version import __version__

# banner frame, '=' lines at the top / bottom only
FRAME = Box(
    "====\n"
    "    \n"
    "    \n"
    "    \n"
    "    \n"
    "    \n"
    "    \n"
    "====\n",
    ascii=True,
)

CD_ART = r"""
      _...::::::..._
   .::::::::::::::::::.
 .::::::::``__``::::::::.
 |:::::(   (__)   ):::::|
 \:::::::..____..:::::::/
  '::::::::::::::::::::'
    `--::::::::::::--`
         ````````
"""


def _build_time() -> str:
    """
        build timestamp generated by build.cmd, 'dev' when running from source.
    """

    # build_info.py also exists in the source folder after a build, so it is only trusted inside the exe
    if not getattr(sys, "frozen", False):
        return "dev (running from source)"

    try:
        from build_info import BUILD_TIME
        return BUILD_TIME
    except ImportError:
        return "unknown"


def _device() -> str:
    """
        device used by demucs, with the gpu name when cuda is available.
    """

    import torch

    if torch.cuda.is_available():
        return f"cuda - {torch.cuda.get_device_name(0)}"
    return "cpu (no cuda gpu found)"


def print_banner(console: Console):
    """
        prints the cli banner: an ascii cd at the left and the app / system info at the right.
    """

    info = Table(box=None, show_header=False, pad_edge=False)
    info.add_column(style="bold blue", no_wrap=True)
    info.add_column()
    info.add_row("compiled", _build_time())
    info.add_row("os", platform.platform())
    info.add_row("python", platform.python_version())
    info.add_row("cpu cores", str(os.cpu_count()))
    info.add_row("device", _device())

    right = Table.grid()
    right.add_row(Text.assemble(("canopy", "bold blue"), f" v{__version__}"))
    right.add_row("")
    right.add_row(info)

    layout = Table.grid(padding=(0, 3))
    layout.add_row(Text(CD_ART.strip("\n"), style="blue"), right)

    console.print(Panel(layout, box=FRAME, border_style="blue", padding=(1, 2), expand=False))
    console.print()
